# Terraform export (#501 part c, optional): the same steps as the run (Get-KeevaultSetupStep, KsLevels, KsVaultSettings)
# as azurerm/azuread code. Resource group, RBAC Key Vault, groups Read/Write/Admin, role assignments; manual steps as
# comments. Tenant and subscription are variables, never written into the code; the code holds no secrets.

function ConvertTo-KsHcl([string] $Text) {
    # HCL string literal: escape backslash and quote, and keep ${ and %{ from starting an interpolation or directive.
    return '"' + $Text.Replace('\', '\\').Replace('"', '\"').Replace('${', '$${').Replace('%{', '%%{') + '"'
}

function Get-KsTfName([string] $Text) {
    $n = ($Text -replace '[^A-Za-z0-9_]', '_').ToLowerInvariant()
    if ($n -notmatch '^[a-z_]') { $n = "_$n" }
    return $n
}

function ConvertTo-KeevaultSetupTerraform {
    <#
    .SYNOPSIS
        Terraform-Code (azurerm, azuread) aus einem Plan: dieselben Schritte wie das Ausführen, ohne Tenant-Daten und
        ohne Secrets. Tenant und Subscription kommen als Variablen (terraform.tfvars oder -var).
    .EXAMPLE
        ConvertTo-KeevaultSetupTerraform -Plan $plan -Path .\keevault\main.tf
        terraform -chdir=keevault init; terraform -chdir=keevault plan -var tenant_id=... -var subscription_id=...
    #>
    [CmdletBinding(SupportsShouldProcess)]
    param([Parameter(Mandatory, Position = 0)] $Plan, [string] $Path)
    $check = Test-KeevaultSetupPlan $Plan
    if (-not $check.Valid) { throw (KsT 'plan.invalid' ($check.Errors -join ' ')) }
    $p = $check.Plan
    $steps = @(Get-KeevaultSetupStep $p)
    $on = { param([string] $Key) [bool] $p.steps[$Key] }
    $tf = New-Object System.Collections.Generic.List[string]
    $add = { param([string] $Line) $tf.Add($Line) }

    & $add '# Keevault: Azure Key Vault, Entra groups and roles (generated by the Keevault setup tool, #501).'
    & $add "# $(KsT 'tf.header')"
    & $add ''
    & $add 'terraform {'
    & $add '  required_version = ">= 1.5"'
    & $add '  required_providers {'
    & $add '    azurerm = {'
    & $add '      source  = "hashicorp/azurerm"'
    & $add '      version = "~> 4.50"'
    & $add '    }'
    & $add '    azuread = {'
    & $add '      source  = "hashicorp/azuread"'
    & $add '      version = "~> 3.0"'
    & $add '    }'
    & $add '  }'
    & $add '}'
    & $add ''
    foreach ($v in @(@('tenant_id', 'Entra ID tenant (GUID)', ''), @('subscription_id', 'Azure subscription (GUID)', ''), @('location', 'Azure region', $p.target.location), @('resource_group_name', 'Resource group of the Keevault vaults', $p.resourceGroup))) {
        & $add "variable `"$($v[0])`" {"
        & $add '  type        = string'
        & $add "  description = $(ConvertTo-KsHcl $v[1])"
        if ($v[2]) { & $add "  default     = $(ConvertTo-KsHcl $v[2])" }
        & $add '}'
        & $add ''
    }
    & $add 'provider "azurerm" {'
    & $add '  features {}'
    & $add '  tenant_id       = var.tenant_id'
    & $add '  subscription_id = var.subscription_id'
    & $add '}'
    & $add ''
    & $add 'provider "azuread" {'
    & $add '  tenant_id = var.tenant_id'
    & $add '}'
    & $add ''

    $rg = 'azurerm_resource_group.keevault'
    if (& $on 'resourceGroup') {
        & $add "# $(@($steps | Where-Object { $_.Key -eq 'resourceGroup' })[0].Title)"
        & $add 'resource "azurerm_resource_group" "keevault" {'
        & $add '  name     = var.resource_group_name'
        & $add '  location = var.location'
        & $add '}'
        & $add ''
    }
    elseif ((& $on 'vaults') -and @($p.vaults).Count) {
        $rg = 'data.azurerm_resource_group.keevault'
        & $add 'data "azurerm_resource_group" "keevault" {'
        & $add '  name = var.resource_group_name'
        & $add '}'
        & $add ''
    }

    foreach ($v in $p.vaults) {
        $id = Get-KsTfName $v.name
        $vaultRef = "azurerm_key_vault.$id"
        if (& $on 'vaults') {
            & $add "# $(@($steps | Where-Object { $_.Id -eq "vault:$($v.name)" })[0].Title)"
            & $add "resource `"azurerm_key_vault`" `"$id`" {"
            & $add "  name                          = $(ConvertTo-KsHcl $v.name)"
            & $add "  location                      = $rg.location"
            & $add "  resource_group_name           = $rg.name"
            & $add '  tenant_id                     = var.tenant_id'
            & $add "  sku_name                      = $(ConvertTo-KsHcl $script:KsVaultSettings.Sku)"
            & $add '  rbac_authorization_enabled    = true'
            & $add "  soft_delete_retention_days    = $([int] $script:KsVaultSettings.SoftDeleteDays)"
            & $add "  purge_protection_enabled      = $(([string] [bool] $script:KsVaultSettings.PurgeProtection).ToLowerInvariant())"
            & $add "  public_network_access_enabled = $(([string] ($script:KsVaultSettings.PublicNetworkAccess -eq 'Enabled')).ToLowerInvariant())"
            & $add '  tags = {'
            & $add '    kvpwsafe        = "container"'
            & $add "    `"kvpwsafe-name`" = $(ConvertTo-KsHcl $v.displayName)"
            & $add '  }'
            & $add '}'
            & $add ''
        }
        elseif (& $on 'roles') {
            $vaultRef = "data.azurerm_key_vault.$id"
            & $add "data `"azurerm_key_vault`" `"$id`" {"
            & $add "  name                = $(ConvertTo-KsHcl $v.name)"
            & $add '  resource_group_name = var.resource_group_name'
            & $add '}'
            & $add ''
        }

        $groupRef = @{}
        if (& $on 'groups') { & $add "# $(@($steps | Where-Object { $_.Id -eq "groups:$($v.name)" })[0].Title)" }
        foreach ($level in $script:KsLevels.Keys) {
            $gid = Get-KsTfName "$($v.name)_$level"
            $name = Get-KsGroupName $p $v.name $level
            if (& $on 'groups') {
                $groupRef[$level] = "azuread_group.$gid"
                & $add "resource `"azuread_group`" `"$gid`" {"
                & $add "  display_name            = $(ConvertTo-KsHcl $name)"
                & $add "  description             = $(ConvertTo-KsHcl (KsT 'read.groupDesc' $level $v.name))"
                & $add '  security_enabled        = true'
                & $add '  mail_enabled            = false'
                & $add '  prevent_duplicate_names = true'
                & $add '}'
                & $add ''
            }
            elseif (& $on 'roles') {
                $groupRef[$level] = "data.azuread_group.$gid"
                & $add "data `"azuread_group`" `"$gid`" {"
                & $add "  display_name     = $(ConvertTo-KsHcl $name)"
                & $add '  security_enabled = true'
                & $add '}'
                & $add ''
            }
        }

        if (& $on 'roles') {
            & $add "# $(@($steps | Where-Object { $_.Id -eq "roles:$($v.name)" })[0].Title) – $(KsT 'tf.import')"
            foreach ($level in $script:KsLevels.Keys) {
                foreach ($role in $script:KsLevels[$level]) {
                    # Same names in every language: the key of the role in KsRole (SecretsUser, Reader ...).
                    $roleKey = @($script:KsRole.Keys | Where-Object { $script:KsRole[$_] -eq $role })[0]
                    $rid = Get-KsTfName "$($v.name)_$($level)_$roleKey"
                    & $add "resource `"azurerm_role_assignment`" `"$rid`" {"
                    & $add "  scope              = $vaultRef.id"
                    & $add "  role_definition_id = `"/subscriptions/`${var.subscription_id}/providers/Microsoft.Authorization/roleDefinitions/$role`""
                    & $add "  principal_id       = $($groupRef[$level]).object_id"
                    & $add '  principal_type     = "Group"'
                    & $add '}'
                    & $add ''
                }
            }
        }
    }

    $manual = @($steps | Where-Object { $_.Kind -eq 'manual' -and $_.Selected })
    if ($manual.Count) {
        & $add "# $(KsT 'tf.manual')"
        foreach ($st in $manual) { & $add "#   - $($st.Title -replace '[\r\n]+', ' ')" }
    }
    $text = ($tf -join "`n") + "`n"
    $why = Test-KsSecretLike $text
    if ($why) { throw (KsT 'tf.secret' $why) }
    if ($Path -and $PSCmdlet.ShouldProcess($Path, (KsT 'tf.write'))) {
        [System.IO.File]::WriteAllText($Path, $text, (New-Object System.Text.UTF8Encoding $false))
    }
    return $text
}
