export function formatDateTime(value) {
  const d = value instanceof Date ? value : new Date(value);
  return Number.isNaN(d.getTime()) || d.getTime() === 0 ? '–' : new Intl.DateTimeFormat(locale(), { dateStyle: 'medium', timeStyle: 'short' }).format(d);
}

// Deterministic avatar color from a string.
export function avatar(title, cls = 'avatar', image = '') {
  if (image) return h('span', { class: `${cls} has-image` }, h('img', { src: image, alt: '' }));
  const text = String(title || '?').trim();
  let hash = 0;
  for (const ch of text) hash = (hash * 31 + ch.charCodeAt(0)) >>> 0;
  return h('span', { class: cls, style: { background: `hsl(${hash % 360} 55% 45%)` } }, text.slice(0, 1).toUpperCase() || '?');
}

export function clear(el) {
  while (el.firstChild) el.firstChild.remove();
  return el;
}

/** replaceChildren that flattens arrays and skips null/false (like h()). */
export function setChildren(el, ...children) {
  el.replaceChildren(...children.flat(Infinity).filter((c) => c != null && c !== false));
  return el;
}

let toastTimer;
export function toast(message, kind = 'info') {
  let el = document.getElementById('toast');
  if (!el) {
    el = h('div', { id: 'toast', role: 'status' });
    document.body.append(el);
  }
  el.textContent = message;
  el.className = `toast show ${kind}`;
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => el.classList.remove('show'), kind === 'error' ? 6000 : 2500);
}

/** Simple modal dialog. content: Node, buttons: [{ label, primary, danger, onClick → false keeps open }] */
export function modal(title, content, buttons = [{ label: t('Schließen') }]) {
  const dialog = h('dialog', { class: 'modal' });
  const close = () => {
    dialog.close();
    dialog.remove();
  };
  const footer = h('div', { class: 'modal-footer' }, ...buttons.map((b) => h('button', {
    type: 'button',
    class: b.primary ? 'btn primary' : b.danger ? 'btn danger' : 'btn',
    onclick: async (e) => {
      const btn = e.currentTarget;
      btn.disabled = true;
      try {
        if ((await b.onClick?.()) !== false) close();
      } catch (err) {
        toast(err.message, 'error');
      } finally {
        btn.disabled = false;
      }
    },
  }, b.label)));
  dialog.append(h('div', { class: 'modal-head' }, h('h3', {}, title), iconButton('x', t('Schließen'), close)), h('div', { class: 'modal-body' }, content), footer);
  dialog.addEventListener('cancel', (e) => {
    e.preventDefault();
    close();
  });
  document.body.append(dialog);
  dialog.showModal();
  return { dialog, close };
}

export function confirmDialog(title, text, { confirmLabel = t('OK'), danger = false } = {}) {
  return new Promise((resolve) => {
    let answered = false;
    const { dialog } = modal(title, h('p', {}, text), [
      { label: t('Abbrechen'), onClick: () => { answered = true; resolve(false); } },
      { label: confirmLabel, primary: !danger, danger, onClick: () => { answered = true; resolve(true); } },
    ]);
    dialog.addEventListener('close', () => { if (!answered) resolve(false); });
  });
}
